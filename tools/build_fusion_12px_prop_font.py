#!/usr/bin/env python3
"""Build the single Fusion Pixel 12px proportional OLED subset.

Usage:
  python3 tools/build_fusion_12px_prop_font.py /path/to/fusion-pixel-12px-proportional

The directory must contain fusion-pixel-12px-proportional-zh_hans.bdf.
Only local BDF input is used; nothing is downloaded by this script.
"""
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
GLYPH_ALIASES = {0x2716: 0x00d7}


def read_bdf(path):
    glyphs = {}
    ascent = descent = None
    current = None
    bitmap = False
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith('FONT_ASCENT '):
            ascent = int(line.split()[1])
        elif line.startswith('FONT_DESCENT '):
            descent = int(line.split()[1])
        elif line.startswith('STARTCHAR '):
            current = {'rows': []}
            bitmap = False
        elif line.startswith('ENCODING '):
            current['code'] = int(line.split()[1])
        elif line.startswith('DWIDTH '):
            current['advance'] = int(line.split()[1])
        elif line.startswith('BBX '):
            current['box'] = tuple(map(int, line.split()[1:]))
        elif line == 'BITMAP':
            bitmap = True
        elif line == 'ENDCHAR':
            glyphs[current['code']] = current
            bitmap = False
        elif bitmap:
            current['rows'].append(line)
    if ascent is None or descent is None:
        raise ValueError(f'{path}: missing FONT_ASCENT/FONT_DESCENT')
    return glyphs, ascent, descent


def corpus():
    chars = set(map(chr, range(32, 127)))
    for name in ('home_zh.h', 'ui_zh.h', 'settings_menu.h', 'oled.cpp'):
        for literal in re.findall(r'"([^"\n]*)"', (ROOT / 'src' / name).read_text(encoding='utf-8')):
            if any(ord(ch) > 126 for ch in literal):
                chars.update(literal)
    return chars


def write_font(source, destination, chars):
    glyphs, ascent, descent = read_bdf(source)
    missing = sorted(ch for ch in chars
                     if ord(ch) not in glyphs and ord(ch) not in GLYPH_ALIASES)
    if missing:
        raise ValueError(f'{source.name}: missing {len(missing)} characters: {"".join(missing)}')
    for alias, target in GLYPH_ALIASES.items():
        if target not in glyphs:
            raise ValueError(f'{source.name}: alias target U+{target:04x} is missing')

    index = bytearray()
    bitmap = bytearray()
    for ch in sorted(chars):
        cp = ord(ch)
        glyph = glyphs[cp] if cp in glyphs else glyphs[GLYPH_ALIASES[cp]]
        width, height, xoff, yoff = glyph['box']
        data = b''.join(bytes.fromhex(row) for row in glyph['rows'])
        assert len(data) == (width + 7) // 8 * height, (source, ch, glyph['box'])
        index.extend(struct.pack('<IIBBbbB', cp, len(bitmap), width, height,
                                 xoff, yoff, glyph['advance']))
        bitmap.extend(data)

    lines = [
        '// Derived bitmap subset: Fusion Pixel Font 12px Proportional, OFL-1.1.',
        '// Release 2026.10.25; see FUSION_PIXEL_OFL.txt and FUSION_PIXEL_LICENSES/.',
        '// Generated by tools/build_fusion_12px_prop_font.py; do not edit.',
        '#pragma once',
        '#include <cstdint>',
        'namespace oled_12px_proportional {',
        f'inline constexpr int ascent = {ascent}, descent = {descent};',
        f'inline constexpr uint32_t count = {len(chars)};',
        'inline constexpr uint8_t index[] = {',
    ]
    lines += [','.join(f'0x{value:02x}' for value in index[i:i + 26]) + ','
              for i in range(0, len(index), 26)]
    lines += ['};', 'inline constexpr uint8_t bitmap[] = {']
    lines += [','.join(f'0x{value:02x}' for value in bitmap[i:i + 24]) + ','
              for i in range(0, len(bitmap), 24)]
    lines += ['};', '}', '']
    destination.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{destination.name}: {len(chars)} glyphs, {len(bitmap)} bitmap bytes, '
          f'ascent {ascent}, descent {descent}')


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    font_dir = Path(sys.argv[1])
    write_font(font_dir / 'fusion-pixel-12px-proportional-zh_hans.bdf',
               ROOT / 'src/oled_zh_prop.h', corpus())


if __name__ == '__main__':
    main()
